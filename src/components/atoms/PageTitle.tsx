import type { ReactNode } from "react";

/**
 * 화면에 제목을 «그리지 않기로 한» page 의 문서 제목.
 *
 * ## 왜 필요한가
 *
 * `<h1>` 을 내는 자리가 `PageHeader` 하나뿐이었고, 그것을 쓰는 화면은 전부 상세거나
 * 패널이다. 그래서 `<h1>` 의 유무가 「이 화면에 제목이 있는가」가 아니라 **「이 화면이
 * 상세인가」**를 따라갔다 — 목록 화면은 문서 전체에 heading 이 **0개**이고, 설정·멤버는
 * `<h1>` 없이 `<h2>` 부터 시작했다. heading 으로 훑는 사람에게 그 화면들은 「제목이 없는
 * 문서」이거나 「최상위가 여러 개인 문서」다.
 *
 * ## 🔴 제목을 «다시 그리는» 것이 아니다
 *
 * 목록 화면이 제목을 비워 둔 것은 실수가 아니라 판단이다 — 사이드바에서 「이슈」를 눌러
 * 들어온 화면의 맨 위 「이슈」는 정보를 더하지 않는다. 그 판단을 지키면서 **접근성 트리에는
 * 남긴다.** 화면은 그대로이고 문서 구조만 선다.
 *
 * 🔴 **`PageContainer` 가 무조건 `<h1>` 을 내게 하지 않는다.** 상세 화면은 `PageHeader` 로
 * 이미 내고 있어, 그렇게 하면 최상위 heading 이 둘이 된다. 그래서 «필요한 화면이 직접»
 * 세운다 — 빠뜨린 화면은 `page-heading.test.ts` 가 잡는다.
 */
export function PageTitle({ children }: { children: ReactNode }) {
  return <h1 className="sr-only">{children}</h1>;
}
